-- Inventario: stock actual y mínimo por producto, y el kárdex con cada movimiento.
-- Los servicios (unidad ZZ u HUR) no manejan stock: siempre quedan en cero.
ALTER TABLE productos ADD COLUMN stock NUMERIC(12, 3) DEFAULT 0 NOT NULL;
ALTER TABLE productos ADD COLUMN stock_minimo NUMERIC(12, 3) DEFAULT 0 NOT NULL;
ALTER TABLE productos ADD CONSTRAINT ck_productos_stock CHECK (stock >= 0 AND stock_minimo >= 0);

-- Cada fila es una entrada o una salida (cantidad siempre positiva) con el saldo que dejó.
-- Las ventas, anulaciones y notas de crédito guardan la venta; los ingresos por compra, la compra.
CREATE TABLE movimientos_stock (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    producto_id     BIGINT         NOT NULL,
    fecha           TIMESTAMP      NOT NULL,
    tipo            VARCHAR(7)     NOT NULL,
    motivo          VARCHAR(25)    NOT NULL,
    cantidad        NUMERIC(12, 3) NOT NULL,
    saldo           NUMERIC(12, 3) NOT NULL,
    venta_id        BIGINT,
    compra_id       BIGINT,
    referencia      VARCHAR(80),
    observacion     VARCHAR(200),
    registrado_por  VARCHAR(50),
    CONSTRAINT fk_movimientos_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT fk_movimientos_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT fk_movimientos_compra FOREIGN KEY (compra_id) REFERENCES compras (id),
    CONSTRAINT ck_movimientos_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA')),
    CONSTRAINT ck_movimientos_motivo CHECK (motivo IN ('SALDO_INICIAL', 'COMPRA', 'DEVOLUCION_CLIENTE',
        'ANULACION_VENTA', 'VENTA', 'DEVOLUCION_PROVEEDOR', 'MERMA', 'CONSUMO_INTERNO', 'AJUSTE', 'OTRO')),
    CONSTRAINT ck_movimientos_cantidad CHECK (cantidad > 0 AND saldo >= 0)
);
CREATE INDEX idx_movimientos_producto ON movimientos_stock (producto_id, fecha);
CREATE INDEX idx_movimientos_venta ON movimientos_stock (venta_id);
CREATE INDEX idx_movimientos_compra ON movimientos_stock (compra_id);
