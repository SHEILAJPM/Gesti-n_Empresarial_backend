-- Esquema inicial (PostgreSQL / Neon). Refleja las entidades JPA existentes:
-- Hibernate arranca con ddl-auto=validate, así que cualquier cambio de tabla va en una nueva migración V2, V3...

CREATE TABLE usuarios (
    id       BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    username VARCHAR(50)  NOT NULL,
    password VARCHAR(100) NOT NULL,
    rol      VARCHAR(20)  NOT NULL,
    activo   BOOLEAN      NOT NULL DEFAULT TRUE,
    CONSTRAINT uk_usuarios_username UNIQUE (username)
);

CREATE TABLE configuracion_tributaria (
    id      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo  VARCHAR(10)   NOT NULL,
    tasa    NUMERIC(5, 4) NOT NULL,
    vigente BOOLEAN       NOT NULL,
    CONSTRAINT uk_configuracion_codigo UNIQUE (codigo)
);

-- Personal

CREATE TABLE trabajadores (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombres             VARCHAR(255),
    documento_identidad VARCHAR(255),
    cargo               VARCHAR(255),
    area                VARCHAR(255),
    estado              VARCHAR(255)
);

CREATE INDEX idx_trabajadores_documento ON trabajadores (documento_identidad);

CREATE TABLE marcaciones (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajador_id BIGINT       NOT NULL,
    tipo          VARCHAR(255) NOT NULL,
    fecha_hora    TIMESTAMP    NOT NULL,
    CONSTRAINT fk_marcaciones_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id),
    CONSTRAINT ck_marcaciones_tipo CHECK (tipo IN ('ENTRADA', 'SALIDA'))
);

CREATE INDEX idx_marcaciones_trabajador ON marcaciones (trabajador_id, fecha_hora);

CREATE TABLE documentos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajador_id     BIGINT       NOT NULL,
    tipo              VARCHAR(255) NOT NULL,
    fecha_vencimiento DATE         NOT NULL,
    CONSTRAINT fk_documentos_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id)
);

CREATE INDEX idx_documentos_trabajador ON documentos (trabajador_id);

-- Proveedores y compras

CREATE TABLE proveedores (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    ruc          VARCHAR(11)  NOT NULL,
    razon_social VARCHAR(150) NOT NULL,
    direccion    VARCHAR(200),
    CONSTRAINT uk_proveedores_ruc UNIQUE (ruc)
);

CREATE TABLE compras (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    proveedor_id       BIGINT         NOT NULL,
    numero_comprobante VARCHAR(20)    NOT NULL,
    fecha              DATE           NOT NULL,
    monto_sin_igv      NUMERIC(12, 2) NOT NULL,
    igv                NUMERIC(12, 2) NOT NULL,
    monto_total        NUMERIC(12, 2) NOT NULL,
    tasa_aplicada      NUMERIC(5, 4)  NOT NULL,
    CONSTRAINT fk_compras_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id),
    CONSTRAINT uk_compras_proveedor_numero UNIQUE (proveedor_id, numero_comprobante)
);

CREATE INDEX idx_compras_fecha ON compras (fecha);

-- Clientes y ventas

CREATE TABLE clientes (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    documento      VARCHAR(11)  NOT NULL,
    nombre         VARCHAR(150) NOT NULL,
    tipo_documento VARCHAR(3)   NOT NULL,
    CONSTRAINT uk_clientes_documento UNIQUE (documento),
    CONSTRAINT ck_clientes_tipo_documento CHECK (tipo_documento IN ('DNI', 'RUC'))
);

CREATE TABLE ventas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    cliente_id         BIGINT         NOT NULL,
    tipo_comprobante   VARCHAR(7)     NOT NULL,
    numero_comprobante VARCHAR(20)    NOT NULL,
    fecha              DATE           NOT NULL,
    monto_sin_igv      NUMERIC(12, 2) NOT NULL,
    igv                NUMERIC(12, 2) NOT NULL,
    monto_total        NUMERIC(12, 2) NOT NULL,
    tasa_aplicada      NUMERIC(5, 4)  NOT NULL,
    estado             VARCHAR(7)     NOT NULL,
    CONSTRAINT fk_ventas_cliente FOREIGN KEY (cliente_id) REFERENCES clientes (id),
    CONSTRAINT uk_ventas_numero UNIQUE (numero_comprobante),
    CONSTRAINT ck_ventas_tipo_comprobante CHECK (tipo_comprobante IN ('FACTURA', 'BOLETA')),
    CONSTRAINT ck_ventas_estado CHECK (estado IN ('EMITIDA', 'ANULADA'))
);

CREATE INDEX idx_ventas_fecha ON ventas (fecha);

-- Pagos (a trabajadores o a proveedores)

CREATE TABLE pagos (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo_beneficiario VARCHAR(20)    NOT NULL,
    trabajador_id     BIGINT,
    proveedor_id      BIGINT,
    concepto          VARCHAR(250)   NOT NULL,
    monto             NUMERIC(15, 2) NOT NULL,
    fecha_programada  DATE           NOT NULL,
    fecha_pago        TIMESTAMP,
    estado            VARCHAR(20)    NOT NULL,
    CONSTRAINT fk_pagos_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id),
    CONSTRAINT fk_pagos_proveedor FOREIGN KEY (proveedor_id) REFERENCES proveedores (id)
);

CREATE INDEX idx_pagos_fecha_programada ON pagos (fecha_programada);
