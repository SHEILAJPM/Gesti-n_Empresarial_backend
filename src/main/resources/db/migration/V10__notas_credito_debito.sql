-- Notas de crédito (07) y de débito (08) que modifican una factura o boleta ya emitida.
-- Serie: F o B según el comprobante afectado + C (crédito) o D (débito) + 01  →  FC01, BC01, FD01, BD01.
-- motivo_codigo: catálogo 09 (crédito) o 10 (débito) de SUNAT.
CREATE TABLE notas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    tipo               VARCHAR(7)     NOT NULL,
    venta_id           BIGINT         NOT NULL,
    numero             VARCHAR(20)    NOT NULL,
    fecha              DATE           NOT NULL,
    motivo_codigo      VARCHAR(2)     NOT NULL,
    sustento           VARCHAR(250)   NOT NULL,
    monto_sin_igv      NUMERIC(12, 2) NOT NULL,
    igv                NUMERIC(12, 2) NOT NULL,
    monto_total        NUMERIC(12, 2) NOT NULL,
    tasa_aplicada      NUMERIC(5, 4)  NOT NULL,
    registrada_por     VARCHAR(50),
    sunat_estado       VARCHAR(12)    DEFAULT 'NO_ENVIADO' NOT NULL,
    sunat_proveedor    VARCHAR(12),
    sunat_document_id  VARCHAR(60),
    sunat_file_name    VARCHAR(40),
    sunat_mensaje      VARCHAR(500),
    sunat_xml_url      VARCHAR(300),
    sunat_cdr_url      VARCHAR(300),
    sunat_fecha_envio  TIMESTAMP,
    CONSTRAINT uk_notas_numero UNIQUE (numero),
    CONSTRAINT fk_notas_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT ck_notas_tipo CHECK (tipo IN ('CREDITO', 'DEBITO')),
    CONSTRAINT ck_notas_sunat_estado
        CHECK (sunat_estado IN ('NO_ENVIADO', 'PENDIENTE', 'ACEPTADO', 'RECHAZADO', 'EXCEPCION', 'ERROR'))
);
CREATE INDEX idx_notas_venta ON notas (venta_id);
CREATE INDEX idx_notas_fecha ON notas (fecha);

CREATE TABLE nota_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nota_id          BIGINT         NOT NULL,
    orden            INTEGER        NOT NULL,
    codigo           VARCHAR(30),
    descripcion      VARCHAR(250)   NOT NULL,
    unidad           VARCHAR(3)     NOT NULL,
    cantidad         NUMERIC(12, 3) NOT NULL,
    valor_unitario   NUMERIC(12, 2) NOT NULL,
    valor_venta      NUMERIC(12, 2) NOT NULL,
    igv              NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_nota_items_nota FOREIGN KEY (nota_id) REFERENCES notas (id) ON DELETE CASCADE,
    CONSTRAINT ck_nota_items_cantidad CHECK (cantidad > 0)
);
CREATE INDEX idx_nota_items_nota ON nota_items (nota_id);
