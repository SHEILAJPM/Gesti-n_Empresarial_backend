-- Catálogo de productos y servicios. valor_unitario es el precio SIN IGV.
-- unidad: catálogo 03 de SUNAT (NIU unidad, ZZ servicio, KGM kilogramo, ...)
CREATE TABLE productos (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo           VARCHAR(30)    NOT NULL,
    descripcion      VARCHAR(250)   NOT NULL,
    unidad           VARCHAR(3)     DEFAULT 'NIU' NOT NULL,
    valor_unitario   NUMERIC(12, 2) NOT NULL,
    activo           BOOLEAN        DEFAULT TRUE NOT NULL,
    CONSTRAINT uk_productos_codigo UNIQUE (codigo),
    CONSTRAINT ck_productos_valor CHECK (valor_unitario >= 0)
);

-- Líneas de cada comprobante. Se copian código, descripción y precio: la factura emitida no cambia
-- aunque después se edite el producto. Las ventas anteriores no tienen líneas y se muestran con una genérica.
CREATE TABLE venta_items (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT         NOT NULL,
    orden            INTEGER        NOT NULL,
    producto_id      BIGINT,
    codigo           VARCHAR(30),
    descripcion      VARCHAR(250)   NOT NULL,
    unidad           VARCHAR(3)     NOT NULL,
    cantidad         NUMERIC(12, 3) NOT NULL,
    valor_unitario   NUMERIC(12, 2) NOT NULL,
    valor_venta      NUMERIC(12, 2) NOT NULL,
    igv              NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_venta_items_venta FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT fk_venta_items_producto FOREIGN KEY (producto_id) REFERENCES productos (id),
    CONSTRAINT ck_venta_items_cantidad CHECK (cantidad > 0)
);
CREATE INDEX idx_venta_items_venta ON venta_items (venta_id);

-- Forma de pago (obligatoria en facturas desde 2021) y cuotas cuando es al crédito
ALTER TABLE ventas ADD COLUMN forma_pago VARCHAR(7) DEFAULT 'CONTADO' NOT NULL;
ALTER TABLE ventas ADD CONSTRAINT ck_ventas_forma_pago CHECK (forma_pago IN ('CONTADO', 'CREDITO'));
ALTER TABLE ventas ADD COLUMN observaciones VARCHAR(250);

CREATE TABLE venta_cuotas (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id           BIGINT         NOT NULL,
    numero             INTEGER        NOT NULL,
    fecha_vencimiento  DATE           NOT NULL,
    monto              NUMERIC(12, 2) NOT NULL,
    CONSTRAINT fk_venta_cuotas_venta FOREIGN KEY (venta_id) REFERENCES ventas (id) ON DELETE CASCADE,
    CONSTRAINT ck_venta_cuotas_monto CHECK (monto > 0)
);
CREATE INDEX idx_venta_cuotas_venta ON venta_cuotas (venta_id);
