-- Planilla mensual: RRHH la genera (BORRADOR) y Contabilidad la aprueba (APROBADA), lo que crea un pago por trabajador.
-- Cada detalle guarda una copia de los datos del trabajador para que la boleta no cambie si luego se edita su ficha.

CREATE TABLE planillas (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio              INTEGER        NOT NULL,
    mes               INTEGER        NOT NULL,
    estado            VARCHAR(10)    NOT NULL,
    fecha_generacion  TIMESTAMP      NOT NULL,
    generada_por      VARCHAR(50)    NOT NULL,
    fecha_aprobacion  TIMESTAMP,
    aprobada_por      VARCHAR(50),
    fecha_pago        DATE,
    total_bruto       NUMERIC(14, 2) NOT NULL,
    total_descuentos  NUMERIC(14, 2) NOT NULL,
    total_neto        NUMERIC(14, 2) NOT NULL,
    total_essalud     NUMERIC(14, 2) NOT NULL,
    CONSTRAINT uk_planillas_periodo UNIQUE (anio, mes),
    CONSTRAINT ck_planillas_mes CHECK (mes BETWEEN 1 AND 12),
    CONSTRAINT ck_planillas_estado CHECK (estado IN ('BORRADOR', 'APROBADA'))
);

CREATE TABLE planilla_detalles (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    planilla_id          BIGINT         NOT NULL,
    trabajador_id        BIGINT         NOT NULL,
    nombres              VARCHAR(150)   NOT NULL,
    documento_identidad  VARCHAR(12)    NOT NULL,
    cargo                VARCHAR(100),
    area                 VARCHAR(100),
    fecha_ingreso        DATE           NOT NULL,
    sueldo_base          NUMERIC(12, 2) NOT NULL,
    dias_laborados       INTEGER        NOT NULL,
    remuneracion_bruta   NUMERIC(12, 2) NOT NULL,
    sistema_pension      VARCHAR(3)     NOT NULL,
    afp                  VARCHAR(30),
    tasa_pension         NUMERIC(6, 4)  NOT NULL,
    descuento_pension    NUMERIC(12, 2) NOT NULL,
    essalud              NUMERIC(12, 2) NOT NULL,
    neto                 NUMERIC(12, 2) NOT NULL,
    pago_id              BIGINT,
    CONSTRAINT fk_planilla_detalles_planilla FOREIGN KEY (planilla_id) REFERENCES planillas (id) ON DELETE CASCADE,
    CONSTRAINT fk_planilla_detalles_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id),
    CONSTRAINT fk_planilla_detalles_pago FOREIGN KEY (pago_id) REFERENCES pagos (id),
    CONSTRAINT uk_planilla_detalles_trabajador UNIQUE (planilla_id, trabajador_id)
);

CREATE INDEX idx_planilla_detalles_trabajador ON planilla_detalles (trabajador_id);
