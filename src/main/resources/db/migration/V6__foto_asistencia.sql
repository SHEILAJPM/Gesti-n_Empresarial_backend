-- Foto que el trabajador se toma al marcar desde el portal. Lleva impresa su ubicación, la hora y la distancia a la sede.
-- Se guarda también la de los intentos rechazados: RRHH ve quién intentó marcar y desde dónde.
CREATE TABLE fotos_asistencia (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajador_id  BIGINT       NOT NULL,
    fecha_hora     TIMESTAMP    NOT NULL,
    tipo_mime      VARCHAR(30)  NOT NULL,
    tamano_bytes   INTEGER      NOT NULL,
    contenido      BYTEA        NOT NULL,
    CONSTRAINT fk_fotos_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id)
);

ALTER TABLE marcaciones ADD COLUMN foto_id BIGINT;
ALTER TABLE marcaciones ADD CONSTRAINT fk_marcaciones_foto FOREIGN KEY (foto_id) REFERENCES fotos_asistencia (id);

ALTER TABLE intentos_marcacion ADD COLUMN foto_id BIGINT;
ALTER TABLE intentos_marcacion ADD CONSTRAINT fk_intentos_foto FOREIGN KEY (foto_id) REFERENCES fotos_asistencia (id);
