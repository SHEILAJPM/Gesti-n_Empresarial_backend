-- Cobros de las ventas al crédito. Se aplican a las cuotas de la más antigua a la más nueva.
CREATE TABLE cobros (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    venta_id         BIGINT         NOT NULL,
    fecha            DATE           NOT NULL,
    monto            NUMERIC(12, 2) NOT NULL,
    medio            VARCHAR(15)    NOT NULL,
    referencia       VARCHAR(60),
    registrado_por   VARCHAR(50),
    registrado_en    TIMESTAMP      NOT NULL,
    CONSTRAINT fk_cobros_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT ck_cobros_monto CHECK (monto > 0),
    CONSTRAINT ck_cobros_medio CHECK (medio IN ('EFECTIVO', 'TRANSFERENCIA', 'DEPOSITO', 'TARJETA', 'YAPE_PLIN'))
);
CREATE INDEX idx_cobros_venta ON cobros (venta_id);
CREATE INDEX idx_cobros_fecha ON cobros (fecha);
