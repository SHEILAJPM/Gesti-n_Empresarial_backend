-- Guía de remisión electrónica remitente (tipo 09, serie T001): sustenta el traslado de mercadería.
-- motivo_codigo: catálogo 20 de SUNAT. modalidad: PUBLICO (01, empresa de transporte) o PRIVADO (02, vehículo propio).
CREATE TABLE guias (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    numero                      VARCHAR(20)    NOT NULL,
    fecha_emision               DATE           NOT NULL,
    fecha_traslado              DATE           NOT NULL,
    motivo_codigo               VARCHAR(2)     NOT NULL,
    venta_id                    BIGINT,
    destinatario_tipo_documento VARCHAR(3)     NOT NULL,
    destinatario_documento      VARCHAR(15)    NOT NULL,
    destinatario_nombre         VARCHAR(150)   NOT NULL,
    peso_bruto_kg               NUMERIC(12, 3) NOT NULL,
    numero_bultos               INTEGER,
    modalidad                   VARCHAR(7)     NOT NULL,
    transportista_ruc           VARCHAR(11),
    transportista_razon_social  VARCHAR(150),
    vehiculo_placa              VARCHAR(10),
    conductor_dni               VARCHAR(8),
    conductor_nombres           VARCHAR(150),
    conductor_licencia          VARCHAR(15),
    partida_ubigeo              VARCHAR(6)     NOT NULL,
    partida_direccion           VARCHAR(200)   NOT NULL,
    llegada_ubigeo              VARCHAR(6)     NOT NULL,
    llegada_direccion           VARCHAR(200)   NOT NULL,
    observaciones               VARCHAR(250),
    registrada_por              VARCHAR(50),
    sunat_estado                VARCHAR(12)    DEFAULT 'NO_ENVIADO' NOT NULL,
    sunat_proveedor             VARCHAR(12),
    sunat_document_id           VARCHAR(60),
    sunat_file_name             VARCHAR(40),
    sunat_mensaje               VARCHAR(500),
    sunat_xml_url               VARCHAR(300),
    sunat_cdr_url               VARCHAR(300),
    sunat_fecha_envio           TIMESTAMP,
    CONSTRAINT uk_guias_numero UNIQUE (numero),
    CONSTRAINT fk_guias_venta FOREIGN KEY (venta_id) REFERENCES ventas (id),
    CONSTRAINT ck_guias_modalidad CHECK (modalidad IN ('PUBLICO', 'PRIVADO')),
    CONSTRAINT ck_guias_peso CHECK (peso_bruto_kg > 0),
    CONSTRAINT ck_guias_sunat_estado
        CHECK (sunat_estado IN ('NO_ENVIADO', 'PENDIENTE', 'ACEPTADO', 'RECHAZADO', 'EXCEPCION', 'ERROR'))
);
CREATE INDEX idx_guias_fecha ON guias (fecha_emision);
CREATE INDEX idx_guias_venta ON guias (venta_id);

CREATE TABLE guia_items (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    guia_id      BIGINT         NOT NULL,
    orden        INTEGER        NOT NULL,
    codigo       VARCHAR(30),
    descripcion  VARCHAR(250)   NOT NULL,
    unidad       VARCHAR(3)     NOT NULL,
    cantidad     NUMERIC(12, 3) NOT NULL,
    CONSTRAINT fk_guia_items_guia FOREIGN KEY (guia_id) REFERENCES guias (id) ON DELETE CASCADE,
    CONSTRAINT ck_guia_items_cantidad CHECK (cantidad > 0)
);
CREATE INDEX idx_guia_items_guia ON guia_items (guia_id);
