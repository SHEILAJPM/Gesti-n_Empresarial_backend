-- Portal del trabajador: usuario ligado a su ficha, sede con ubicación y asistencia por GPS.

ALTER TABLE usuarios ADD COLUMN trabajador_id BIGINT;
ALTER TABLE usuarios ADD CONSTRAINT fk_usuarios_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id);
ALTER TABLE usuarios ADD CONSTRAINT uk_usuarios_trabajador UNIQUE (trabajador_id);

-- Punto de la empresa: el trabajador solo marca si está dentro de radio_metros y su GPS es suficientemente preciso
CREATE TABLE sedes (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    nombre            VARCHAR(100)   NOT NULL,
    direccion         VARCHAR(200),
    latitud           NUMERIC(10, 7) NOT NULL,
    longitud          NUMERIC(10, 7) NOT NULL,
    radio_metros      INTEGER        NOT NULL,
    precision_maxima  INTEGER        NOT NULL,
    activa            BOOLEAN        NOT NULL DEFAULT TRUE,
    CONSTRAINT ck_sedes_radio CHECK (radio_metros BETWEEN 5 AND 1000),
    CONSTRAINT ck_sedes_precision CHECK (precision_maxima BETWEEN 5 AND 500)
);

-- RRHH = registrada por Recursos Humanos; PORTAL = marcada por el propio trabajador con su ubicación
ALTER TABLE marcaciones ADD COLUMN origen VARCHAR(10) DEFAULT 'RRHH' NOT NULL;
ALTER TABLE marcaciones ADD COLUMN latitud NUMERIC(10, 7);
ALTER TABLE marcaciones ADD COLUMN longitud NUMERIC(10, 7);
ALTER TABLE marcaciones ADD COLUMN precision_metros NUMERIC(8, 2);
ALTER TABLE marcaciones ADD COLUMN distancia_metros NUMERIC(8, 2);
ALTER TABLE marcaciones ADD CONSTRAINT ck_marcaciones_origen CHECK (origen IN ('RRHH', 'PORTAL'));

-- Intentos de marcar fuera del radio o con GPS impreciso: RRHH los revisa
CREATE TABLE intentos_marcacion (
    id                BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    trabajador_id     BIGINT         NOT NULL,
    fecha_hora        TIMESTAMP      NOT NULL,
    tipo              VARCHAR(10)    NOT NULL,
    latitud           NUMERIC(10, 7) NOT NULL,
    longitud          NUMERIC(10, 7) NOT NULL,
    precision_metros  NUMERIC(8, 2)  NOT NULL,
    distancia_metros  NUMERIC(8, 2)  NOT NULL,
    motivo            VARCHAR(200)   NOT NULL,
    CONSTRAINT fk_intentos_trabajador FOREIGN KEY (trabajador_id) REFERENCES trabajadores (id)
);

CREATE INDEX idx_intentos_fecha ON intentos_marcacion (fecha_hora);
